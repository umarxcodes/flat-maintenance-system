// =====================  AUTHORITY HELPERS  =================
/**
 * Checks if an inviter possesses the authority to grant a target role.
 *
 * Security Invariant:
 * Anti-Privilege Escalation Rule (FR-AUTH-04 / System Invariant):
 * An inviter can NEVER grant a role equal to or higher in authority than their own.
 * E.g., a BUILDING_ADMIN (level 2) cannot invite another BUILDING_ADMIN or a SUPER_ADMIN.
 *
 * @param {string} inviterRole - Role of the inviter.
 * @param {string} targetRole - Role being assigned.
 * @returns {boolean} True if assignment is lawful and non-escalating.
 */
export const canAssignRole = (inviterRole, targetRole) => {
  const inviterLevel = ROLE_HIERARCHY_LEVEL[inviterRole];
  const targetLevel = ROLE_HIERARCHY_LEVEL[targetRole];

  if (!inviterLevel || !targetLevel) {
    return false;
  }

  return inviterLevel < targetLevel;
};
